CREATE TABLE IF NOT EXISTS compartimento (
    id BIGINT PRIMARY KEY CHECK (id BETWEEN 1 AND 5),
    codigo VARCHAR(2) NOT NULL UNIQUE,
    ultimo_tipo VARCHAR(20),
    ultima_data DATE,
    CHECK ((ultimo_tipo IS NULL) = (ultima_data IS NULL))
);

CREATE TABLE IF NOT EXISTS ingrediente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    nome_normalizado VARCHAR(256) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    quantidade NUMERIC(12,3) NOT NULL CHECK (quantidade >= 0),
    compartimento_id BIGINT NOT NULL REFERENCES compartimento(id),
    criado_em TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    UNIQUE (nome_normalizado, tipo, compartimento_id)
);

CREATE TABLE IF NOT EXISTS movimentacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    operacao VARCHAR(10) NOT NULL,
    quantidade NUMERIC(12,3) NOT NULL CHECK (quantidade > 0),
    tipo VARCHAR(20) NOT NULL,
    ingrediente_id BIGINT NOT NULL REFERENCES ingrediente(id),
    ingrediente_nome VARCHAR(120) NOT NULL,
    compartimento_id BIGINT NOT NULL REFERENCES compartimento(id),
    compartimento_codigo VARCHAR(2) NOT NULL,
    responsavel VARCHAR(120) NOT NULL
);
